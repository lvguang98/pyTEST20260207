def _prompts_dir():
    """提示词目录 resource/prompts/"""
    try:
        from path_utils import path_utils
        base = path_utils.resource_dir
    except Exception:
        import sys
        base = os.path.join(os.path.dirname(os.path.abspath(__file__)), "resource")
    prompts_dir = os.path.join(str(base), "prompts")
    os.makedirs(prompts_dir, exist_ok=True)
    return prompts_dir


def load_prompt(key: str) -> str:
    """
    加载指定提示词：
    1. 文件不存在 → 用默认提示词创建一份并返回默认。
    2. 文件存在 → 读取内容（utf-8-sig 兼容记事本 BOM）后 strip 返回。
    3. 文件为空 → 打印告警，返回默认（不覆盖用户文件）。
    """
    default = DEFAULT_PROMPTS.get(key)
    if default is None:
        raise KeyError(f"未知提示词 key: {key}")

    filename = PROMPT_FILES.get(key)
    if filename is None:
        raise KeyError(f"提示词 {key} 未配置文件名")

    prompts_dir = _prompts_dir()
    path = os.path.join(prompts_dir, filename)

    if not os.path.exists(path):
        try:
            with open(path, "w", encoding="utf-8") as f:
                f.write(default)
            print(f"📝 已生成提示词文件: {path}")
        except Exception as e:
            print(f"⚠️ 生成提示词文件失败({path}): {e}")
        return default

    try:
        with open(path, "r", encoding="utf-8-sig") as f:
            content = f.read().strip()
    except Exception as e:
        print(f"⚠️ 读取提示词文件失败({path})，使用默认: {e}")
        return default

    if not content:
        print(f"⚠️ 提示词文件为空({path})，使用默认")
        return default

    return content
