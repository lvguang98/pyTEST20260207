# User Prompt 构建
# ============================================================================

def build_user_prompt(c: CaseClassification,
                     case_statement: str = "",
                     material_summary: str = "") -> str:
    """
    构建 User Prompt —— 传入个案事实。

    事故详情从案件申请陈述中提取（AI自动分析）。
    证据状态来自 UI 材料列表的勾选状态。

    Args:
        c: 案件分类结果
        case_statement: 案件申请陈述（始终传入）
        material_summary: 材料清单（始终传入，✓✗来自UI勾选）

    Returns:
        紧凑格式的 User Prompt 字符串
    """
    p = c.person
    co = c.company
    a = c.accident

    # ── 基本信息 ──
    lines = [
        f"案件：{c.case_nature}，{c.applicant_type}，适用{c.regulation_text}",
        f"角色：{c.role}",
        f"受伤职工：{c.injured_worker_name}",
        "",
        f"人员：{p.name}，{p.gender}，{p.age}岁",
        f"身份证：{p.idcard}" if p.idcard else "身份证：未填写",
        f"地址：{p.id_address}" if p.id_address else "",
        f"电话：{p.phone}" if p.phone else "",
        f"岗位：{p.position}" if p.position else "",
        "",
        f"公司：{co.company_name or '未填写'}",
        f"用人单位：{co.employer}" if co.employer else "",
        f"工地：{co.site}" if co.site else "",
    ]

    # ── 事故信息（优先已提取数据） ──
    has_accident_data = any([a.time, a.location, a.description, a.diagnosis, a.hospital])
    if has_accident_data:
        lines.append("")
        if a.time:
            lines.append(f"事故时间：{a.time}")
        if a.location:
            lines.append(f"事故地点：{a.location}")
        if a.description:
            lines.append(f"受伤经过：{a.description[:200]}")
        if a.diagnosis:
            lines.append(f"诊断结论：{a.diagnosis}")
        if a.hospital:
            lines.append(f"送医医院：{a.hospital}")

    # ── 案件申请陈述（始终传入） ──
    if case_statement:
        lines.append("")
        lines.append("===== 案件申请陈述 =====")
        lines.append(case_statement[:600])
        if not has_accident_data:
            lines.append("")
            lines.append("【重要】请从以上案件申请陈述中提取：事故时间、事故地点、受伤经过、医院诊断、送医医院")

    # ── 材料清单（来自UI勾选状态） ──
    if material_summary:
        lines.append("")
        lines.append("===== 材料清单（✓=已提供, ✗=缺失） =====")
        lines.append(material_summary)

    # ── 非本人：一致性对比 ──
    if c.role != "本人" and case_statement:
        lines.append("")
        lines.append("===== 一致性对比要求 =====")
        lines.append("1. 案件申请陈述为本案已确认的基础事实，请据此生成谈话笔录")
        lines.append("2. 被谈话人陈述与案件申请陈述有出入时，标注【注意：与案件申请陈述不一致】")
        lines.append("3. 关键事实（时间、地点、受伤经过、劳动关系）如有矛盾必须明确指出")

    # ── 证据追问（所有角色） ──
    if material_summary:
        lines.append("")
        lines.append("===== 证据追问要求 =====")
        lines.append("1. 标记为 ✗ 的材料尚未提供，必须在谈话中逐项追问")
        lines.append("2. 关键材料缺失必须明确问：劳动合同、医院诊断证明、工资发放记录、考勤记录、事故现场证据、证人信息")
        lines.append("3. 追问格式：'问：你是否能提供[材料名称]？如不能，请说明原因。'")

    lines.append("")
    lines.append("请根据以上信息生成完整的谈话笔录问答内容。")
    lines.append("已有信息填入回答中作为参考。未掌握的用[待核实]标注。")

    return "\n".join(line for line in lines if line)


